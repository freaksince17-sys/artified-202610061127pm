export const getCraftArticles = (): CraftArticle[] => {
  const authenticCovers = [
    CAVIAR_PEARL_BAG_IMAGE,
    PEARL_BEADED_BAG_IMAGE,
    ROUND_PEARL_BAG_IMAGE,
    CHOKER_PEARL_IMAGE
  ];

  try {
    const saved = localStorage.getItem('artified_craft_articles');
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // Automatically upgrade any old unsplash placeholder covers
        return parsed.map((art: CraftArticle, idx: number) => {
          if (!art.coverImage || art.coverImage.includes('images.unsplash.com') || art.coverImage.includes('photo-1584917865442')) {
            return {
              ...art,
              coverImage: authenticCovers[idx % authenticCovers.length]
            };
          }
          return art;
        });
      }
    }
  } catch {}
  return INITIAL_CRAFT_ARTICLES;
};

export const saveCraftArticle = (newArticle: CraftArticle): CraftArticle[] => {
  const current = getCraftArticles();
  const exists = current.some((a) => a.id === newArticle.id);
  const updated = exists 
    ? current.map((a) => (a.id === newArticle.id ? newArticle : a))
    : [newArticle, ...current];
  
  try {
    localStorage.setItem('artified_craft_articles', JSON.stringify(updated));
    window.dispatchEvent(new CustomEvent('artified_articles_updated', { detail: updated }));
  } catch {}

  return updated;
};
